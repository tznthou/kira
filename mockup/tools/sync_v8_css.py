#!/usr/bin/env python3
"""基準 → app 的三個逐字副本（檔頭記基準 commit，禁止手改）：
  <style>                       → src/styles/v8.css（index.css 放進 components 層）
  <svg width="0" height="0"> 圖示 sprite → src/styles/v8-sprite.svg（App root 以 ?raw + innerHTML 注入一次）
  highlight 區塊（diff 的上色器，Phase 5 Q-H）→ src/lib/v8-highlight.js（後面接一行 export；型別在手寫的
                                  v8-highlight.d.ts，語料在 src/tests/fixtures/highlight-corpus.js）

用法：python3 sync_v8_css.py            產生。基準有未 commit 的改動時拒絕（檔頭要記得出確切的 commit）
      python3 sync_v8_css.py --check    D2：三個檔的本文必須與基準逐字相同。
                                        還沒接進 CI，在本機跑
兩種模式都先檢查：基準定義的 CSS 變數不得落在 Tailwind theme 的命名空間。app 把 v8.css 放進
components 層，與 theme 層同名的變數會蓋掉它、悄悄改掉 utility 的值（Phase 3 spike：--ease-out、
--font-mono）。命名空間從實裝的 tailwindcss/theme.css 推：取變數名的第一段（--font-mono → font），
v8 變數的第一段撞到任何一個就算違規——比手寫列表保守，也跟著 Tailwind 升版自動更新。
"""
import argparse
import re
import subprocess
import sys
from pathlib import Path

TOOLS = Path(__file__).resolve().parent
MOCKUP = TOOLS.parent
REPO = MOCKUP.parent
REF = MOCKUP / "v8-kirazuri-lines-sys.html"
THEME = REPO / "node_modules" / "tailwindcss" / "theme.css"


def git(*args):
    return subprocess.run(["git", "-C", str(MOCKUP), *args], capture_output=True, text=True, check=True).stdout.strip()


def style_block(src):
    blocks = re.findall(r"<style>\n(.*?)</style>\n", src, re.S)
    if len(blocks) != 1 or src.count("<style>") != 1:
        sys.exit(f"expected exactly one <style> block in {REF.name}, found {src.count('<style>')}")
    return blocks[0]


def sprite_block(src):
    # 圖示都是 <symbol>，裡面不會再有 </svg>；只認基準那一個 0×0 的 sprite
    blocks = re.findall(r'^<svg width="0" height="0"[^>]*>\n.*?^</svg>\n', src, re.S | re.M)
    if len(blocks) != 1:
        sys.exit(f'expected exactly one <svg width="0" height="0"> sprite in {REF.name}, found {len(blocks)}')
    return blocks[0]


def highlight_block(src):
    # 兩個標記之間整段照抄（區塊不用頁面上別的東西），後面接 export：基準是一般的 <script>，區塊自己不 export
    blocks = re.findall(r"^  /\* -{10} highlight:.*?^  /\* -{10} end highlight -{10} \*/\n", src, re.S | re.M)
    if len(blocks) != 1:
        sys.exit(f"expected exactly one highlight block in {REF.name}, found {len(blocks)}")
    return blocks[0] + "\nexport { escCode, highlight, langOf };\n"


# 每個副本：輸出檔、檔頭（{ref} {rev}）、從檔頭讀回 commit 的 regex、從基準取本文的函式
COPIES = [
    (
        REPO / "src" / "styles" / "v8.css",
        "/* v8 reference CSS, copied verbatim from mockup/{ref} @ {rev}.\n"
        "   Generated by mockup/tools/sync_v8_css.py; do not edit by hand: change the reference,\n"
        "   commit it, then re-run the script. Loaded in @layer components (src/index.css). */\n\n",
        re.compile(r"\A/\* v8 reference CSS, copied verbatim from mockup/\S+ @ (\w+)\.\n"),
        style_block,
    ),
    (
        REPO / "src" / "styles" / "v8-sprite.svg",
        "<!-- v8 reference icon sprite, copied verbatim from mockup/{ref} @ {rev}.\n"
        "     Generated by mockup/tools/sync_v8_css.py; do not edit by hand: change the reference,\n"
        "     commit it, then re-run the script. An HTML fragment, not a standalone SVG file:\n"
        "     src/App.tsx injects it once at the app root (?raw + innerHTML). -->\n",
        re.compile(r"\A<!-- v8 reference icon sprite, copied verbatim from mockup/\S+ @ (\w+)\.\n"),
        sprite_block,
    ),
    (
        REPO / "src" / "lib" / "v8-highlight.js",
        "// v8 reference highlighter, copied verbatim from mockup/{ref} @ {rev}.\n"
        "// Generated by mockup/tools/sync_v8_css.py; do not edit by hand: change the reference,\n"
        "// commit it, then re-run the script. Types by hand in v8-highlight.d.ts.\n\n",
        re.compile(r"\A// v8 reference highlighter, copied verbatim from mockup/\S+ @ (\w+)\.\n"),
        highlight_block,
    ),
]


def first_segment(name):
    return name[2:].split("-", 1)[0]


def namespace_violations(css):
    if not THEME.exists():
        sys.exit(f"missing {THEME} — run npm install in the repo first")
    taken = {first_segment(n) for n in re.findall(r"^\s*(--[a-z0-9-]+)\s*:", THEME.read_text(encoding="utf-8"), re.M)}
    defined = sorted(set(re.findall(r"(?<![\w-])(--[a-zA-Z0-9-]+)\s*:", css)))
    return defined, [n for n in defined if first_segment(n) in taken], sorted(taken)


def check_copy(out, header_tpl, header_rev, body_ref, rev, dirty):
    rel = out.relative_to(REPO)
    if not out.exists():
        return f"FAIL {rel} does not exist — run without --check to generate it"
    text = out.read_text(encoding="utf-8")
    m = header_rev.match(text)
    header = header_tpl.format(ref=REF.name, rev=m.group(1)) if m else None
    if not header or not text.startswith(header):
        return f"FAIL {rel} has no intact generated header — was it edited by hand?"
    body = text[len(header):]
    where = f"reference @ {rev}{' + uncommitted edits' if dirty else ''}"
    if body != body_ref:
        a_lines, b_lines = body_ref.splitlines(), body.splitlines()
        first = next((i for i in range(max(len(a_lines), len(b_lines))) if a_lines[i:i + 1] != b_lines[i:i + 1]), None)
        return (f"FAIL D2: {rel} (header @ {m.group(1)}) differs from the {where} "
                f"— first difference at line {first + 1 if first is not None else '?'} of the copied block; re-run the script")
    note = "" if m.group(1) == rev and not dirty else f" (header records {m.group(1)}; the copy itself is unchanged)"
    print(f"PASS D2: {rel} matches the {where} byte for byte{note}")
    return None


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--check", action="store_true", help="D2: compare the generated copies with the reference")
    a = ap.parse_args()

    src = REF.read_text(encoding="utf-8")
    defined, bad, taken = namespace_violations(style_block(src))
    if bad:
        sys.exit(f"FAIL {len(bad)} reference variable(s) sit in a Tailwind theme namespace "
                 f"({', '.join(taken)}): {', '.join(bad)} — rename them in the reference")
    print(f"namespaces: {len(defined)} variables, none in Tailwind's ({len(taken)} prefixes from {THEME.name})")

    # 記最後一次改到基準檔的 commit，不記 HEAD：只動工具的 commit 不該讓重產的副本多出檔頭 diff
    rev = git("log", "-1", "--format=%h", "--", REF.name)
    dirty = bool(git("status", "--porcelain", "--", REF.name))

    if not a.check:
        if dirty:
            sys.exit(f"{REF.name} has uncommitted changes — commit the reference first, so the header names it")
        for out, header_tpl, _, extract in COPIES:
            body = extract(src)
            out.parent.mkdir(parents=True, exist_ok=True)
            out.write_text(header_tpl.format(ref=REF.name, rev=rev) + body, encoding="utf-8")
            print(f"wrote {out.relative_to(REPO)} from {REF.name} @ {rev} ({len(body)} chars)")
        return

    failures = [f for out, header_tpl, header_rev, extract in COPIES
                if (f := check_copy(out, header_tpl, header_rev, extract(src), rev, dirty))]
    if failures:
        sys.exit("\n".join(failures))


if __name__ == "__main__":
    main()
